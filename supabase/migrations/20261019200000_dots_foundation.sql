-- ============================================================================
-- Atomic Proposal Approval RPC Function
-- ============================================================================
CREATE OR REPLACE FUNCTION public.dots_approve_proposal(
    p_proposal_id TEXT,
    p_chat_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_proposal RECORD;
    v_current_slots JSONB;
    v_item JSONB;
    v_is_stale BOOLEAN := false;
BEGIN
    -- 0. Validate parameters
    IF p_proposal_id IS NULL OR length(trim(p_proposal_id)) = 0 THEN
        RETURN jsonb_build_object('success', false, 'status', 'invalid_argument', 'message', 'Invalid proposal ID.');
    END IF;

    -- 1. Resolve user by telegram chat_id
    SELECT id INTO v_user_id FROM public.dots_users WHERE telegram_chat_id = p_chat_id;
    IF v_user_id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'status', 'unauthorized', 'message', 'User not found for this Telegram account.');
    END IF;

    -- 2. Lock proposal row for atomic transition
    SELECT * INTO v_proposal
    FROM public.dots_schedule_proposals
    WHERE id = p_proposal_id AND user_id = v_user_id
    FOR UPDATE;

    IF v_proposal IS NULL THEN
        RETURN jsonb_build_object('success', false, 'status', 'not_found', 'message', 'Proposal not found.');
    END IF;

    IF v_proposal.status <> 'pending' THEN
        RETURN jsonb_build_object('success', false, 'status', v_proposal.status, 'message', format('Proposal is already %s.', v_proposal.status));
    END IF;

    -- 3. Stale Detection Check: Fetch current schedule as JSON
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id', id,
        'startTime', start_time,
        'endTime', end_time,
        'durationMinutes', duration_minutes
    ) ORDER BY start_time ASC), '[]'::jsonb)
    INTO v_current_slots
    FROM public.dots_scheduled_slots
    WHERE user_id = v_user_id AND date = v_proposal.target_date;

    -- Compare count of current slots vs base snapshot count
    IF jsonb_array_length(v_current_slots) <> jsonb_array_length(v_proposal.base_schedule_snapshot) THEN
        v_is_stale := true;
    ELSE
        -- Deep comparison of slots
        IF v_current_slots::text <> v_proposal.base_schedule_snapshot::text THEN
            v_is_stale := true;
        END IF;
    END IF;

    IF v_is_stale THEN
        UPDATE public.dots_schedule_proposals SET status = 'stale', resolved_at = now() WHERE id = p_proposal_id;
        RETURN jsonb_build_object('success', false, 'status', 'stale', 'message', 'Schedule changed before approval. Proposal is stale.');
    END IF;

    -- 4. Atomically apply proposed schedule
    -- Delete all non-locked slots for this target date
    DELETE FROM public.dots_scheduled_slots
    WHERE user_id = v_user_id AND date = v_proposal.target_date AND locked = false;

    -- Insert new non-locked slots from proposed_schedule
    FOR v_item IN SELECT * FROM jsonb_array_elements(v_proposal.proposed_schedule)
    LOOP
        IF NOT COALESCE((v_item->>'locked')::boolean, false) THEN
            INSERT INTO public.dots_scheduled_slots (
                id,
                user_id,
                work_item_id,
                title,
                date,
                start_time,
                end_time,
                duration_minutes,
                session_index,
                total_sessions,
                is_split,
                locked,
                reason,
                created_at,
                updated_at
            ) VALUES (
                v_item->>'id',
                v_user_id,
                v_item->>'workItemId',
                v_item->>'title',
                v_proposal.target_date,
                v_item->>'startTime',
                v_item->>'endTime',
                (v_item->>'durationMinutes')::int,
                COALESCE((v_item->>'sessionIndex')::int, 1),
                COALESCE((v_item->>'totalSessions')::int, 1),
                COALESCE((v_item->>'isSplit')::boolean, false),
                false,
                v_item->>'reason',
                now(),
                now()
            )
            ON CONFLICT (id) DO UPDATE SET
                start_time = EXCLUDED.start_time,
                end_time = EXCLUDED.end_time,
                duration_minutes = EXCLUDED.duration_minutes,
                updated_at = now();
        END IF;
    END LOOP;

    -- 5. Mark proposal as approved
    UPDATE public.dots_schedule_proposals
    SET status = 'approved', resolved_at = now()
    WHERE id = p_proposal_id;

    RETURN jsonb_build_object(
        'success', true,
        'status', 'approved',
        'message', 'Schedule successfully updated and committed.',
        'targetDate', v_proposal.target_date
    );
END;
$$;

-- ============================================================================
-- Proposal Rejection RPC Function
-- ============================================================================
CREATE OR REPLACE FUNCTION public.dots_reject_proposal(
    p_proposal_id TEXT,
    p_chat_id BIGINT,
    p_reason TEXT DEFAULT 'Rejected by user'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_user_id UUID;
    v_proposal RECORD;
BEGIN
    IF p_proposal_id IS NULL OR length(trim(p_proposal_id)) = 0 THEN
        RETURN jsonb_build_object('success', false, 'status', 'invalid_argument', 'message', 'Invalid proposal ID.');
    END IF;

    SELECT id INTO v_user_id FROM public.dots_users WHERE telegram_chat_id = p_chat_id;
    IF v_user_id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'status', 'unauthorized', 'message', 'User not found for this Telegram account.');
    END IF;

    SELECT * INTO v_proposal
    FROM public.dots_schedule_proposals
    WHERE id = p_proposal_id AND user_id = v_user_id
    FOR UPDATE;

    IF v_proposal IS NULL THEN
        RETURN jsonb_build_object('success', false, 'status', 'not_found', 'message', 'Proposal not found.');
    END IF;

    IF v_proposal.status <> 'pending' THEN
        RETURN jsonb_build_object('success', false, 'status', v_proposal.status, 'message', format('Proposal is already %s.', v_proposal.status));
    END IF;

    UPDATE public.dots_schedule_proposals
    SET status = 'rejected', resolved_at = now()
    WHERE id = p_proposal_id;

    RETURN jsonb_build_object(
        'success', true,
        'status', 'rejected',
        'message', p_reason
    );
END;
$$;
